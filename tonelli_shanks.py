
def tonelli_shanks(a, p):
    # Αναγωγή του a modulo p
    a = a % p

    # Έλεγχος ειδικών περιπτώσεων
    if a == 0:
        return [0]

    # Έλεγχος αν υπάρχει τετραγωνική ρίζα
    if pow(a, (p - 1) // 2, p) != 1:
        return None

    # Βήμα 1: Γράφουμε p - 1 = q * 2^s,
    # όπου q περιττός αριθμός
    q = p - 1
    s = 0

    while q % 2 == 0:
        q //= 2
        s += 1

    # Βήμα 2: Βρίσκουμε έναν μη τετραγωνικό
    # αριθμό z modulo p
    z = 2

    while pow(z, (p - 1) // 2, p) != p - 1:
        z += 1

    # Βήμα 3: Αρχικοποίηση μεταβλητών
    m = s
    c = pow(z, q, p)
    t = pow(a, q, p)
    r = pow(a, (q + 1) // 2, p)

    # Βήμα 4: Επαναληπτική διαδικασία
    while t != 1:

        # Βρίσκουμε το μικρότερο i ώστε
        # t^(2^i) = 1 (mod p)
        i = 1
        temp = (t * t) % p

        while temp != 1:
            temp = (temp * temp) % p
            i += 1

        # Υπολογισμός της δύναμης του c
        b = pow(c, 2 ** (m - i - 1), p)

        # Ενημέρωση μεταβλητών
        m = i
        c = (b * b) % p
        t = (t * c) % p
        r = (r * b) % p

    # Επιστρέφουμε τις δύο τετραγωνικές ρίζες
    return sorted([r, (-r) % p])


# Είσοδος δεδομένων
a = int(input("Δώσε τον αριθμό a: "))
p = int(input("Δώσε τον πρώτο αριθμό p: "))

# Εκτέλεση αλγορίθμου
roots = tonelli_shanks(a, p)

# Εμφάνιση αποτελέσματος
if roots is None:
    print("Δεν υπάρχει τετραγωνική ρίζα.")
else:
    print("Οι τετραγωνικές ρίζες είναι:", roots)
